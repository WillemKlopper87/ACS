#!/usr/bin/env python3
"""Export every device's discovered parameter tree into a per-firmware library.

Writes ci/compatibility/discoveries/<vendor>/<model>/<firmware>/ with:
  meta.json       identity (manufacturer, model, hardware/software version),
                  root, data-model version, counts, objects never observed
  parameters.tsv  path <TAB> RW|RO <TAB> type  (one line per discovered name)
and regenerates ci/compatibility/discoveries/INDEX.md.

Snapshots for the same vendor/model/firmware are UNIONED: CPEs such as the
Nokia FastMile 1.2501.00.0798 drop CWMP sessions at different objects on each
walk, so merging walks (and devices) converges on the complete tree.

Only names, access metadata and identity strings are exported. Device IDs,
serial numbers, OUI+serial keys and parameter VALUES are never written.

Uses ACS_API_TOKEN, like scripts/qualify-device.py.
"""
import argparse
import importlib.util
import json
import os
import re
import time
import urllib.parse
from pathlib import Path

spec = importlib.util.spec_from_file_location("discovery", Path(__file__).with_name("discover-devices.py"))
discovery = importlib.util.module_from_spec(spec)
spec.loader.exec_module(discovery)

IDENTITY_FIELDS = ("Manufacturer", "ModelName", "ProductClass", "HardwareVersion", "SoftwareVersion")
DEFAULT_LIBRARY = Path(__file__).resolve().parent.parent / "ci" / "compatibility" / "discoveries"


def slug(value):
    value = re.sub(r"[^A-Za-z0-9._-]+", "-", (value or "unknown").strip()).strip("-.")
    return value or "unknown"


def list_devices(acs):
    devices, page = [], 1
    while True:
        result = acs.request("/api/v1/devices?page=%d&page_size=200" % page)
        items = result.get("items") or []
        devices.extend(items)
        if not items or len(devices) >= result.get("total", 0):
            return devices
        page += 1


def identity(acs, device, root):
    paths = [root + "DeviceInfo." + f for f in IDENTITY_FIELDS] + [root + "RootDataModelVersion"]
    query = urllib.parse.quote(",".join(paths), safe="")
    cached = acs.request("/api/v1/devices/%s/parameters?paths=%s" % (device["id"], query)).get("parameters") or {}
    value = lambda p: (cached.get(p) or {}).get("value") or ""
    out = {f: value(root + "DeviceInfo." + f) for f in IDENTITY_FIELDS}
    out["RootDataModelVersion"] = value(root + "RootDataModelVersion")
    return out


def skipped_objects(acs, command_key):
    try:
        job = acs.request("/api/v1/jobs/" + urllib.parse.quote(command_key, safe=""))
    except Exception:
        return []
    detail = job.get("result_detail") or {}
    return detail.get("skipped") or [] if isinstance(detail, dict) else []


def load_entry(directory):
    meta, params = {}, {}
    if (directory / "meta.json").exists():
        meta = json.loads((directory / "meta.json").read_text(encoding="utf-8"))
    if (directory / "parameters.tsv").exists():
        for line in (directory / "parameters.tsv").read_text(encoding="utf-8").splitlines():
            if not line or line.startswith("#"):
                continue
            path, access, vtype = (line.split("\t") + ["", ""])[:3]
            params[path] = {"writable": access == "RW", "type": vtype}
    return meta, params


def write_entry(directory, meta, params):
    directory.mkdir(parents=True, exist_ok=True)
    lines = ["# path\taccess\ttype"]
    for path in sorted(params):
        p = params[path]
        lines.append("%s\t%s\t%s" % (path, "RW" if p["writable"] else "RO", p.get("type", "")))
    (directory / "parameters.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (directory / "meta.json").write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_index(library):
    rows = []
    for meta_file in sorted(library.glob("*/*/*/meta.json")):
        m = json.loads(meta_file.read_text(encoding="utf-8"))
        rel = meta_file.parent.relative_to(library).as_posix()
        rows.append("| %s | %s | %s | %s | %s | %s | %d / %d | %d | %s | [%s](%s/) |" % (
            m.get("manufacturer", ""), m.get("model_name", ""), m.get("product_class", ""),
            ", ".join(m.get("hardware_versions", [])), m.get("software_version", ""),
            m.get("root_data_model_version", ""), m.get("parameter_count", 0), m.get("writable_count", 0),
            m.get("snapshots_merged", 0), m.get("last_discovered_at", "")[:10], rel, rel))
    text = ["# Discovered device library", "",
            "Generated by `scripts/export-discovery-library.py`. One entry per vendor / model / firmware;",
            "repeated walks of the same firmware are unioned. Names and access metadata only — no",
            "serial numbers, device IDs or parameter values.", "",
            "| Manufacturer | Model | ProductClass | Hardware | Firmware | TR-181 | Params / writable | Walks merged | Last walk | Entry |",
            "|---|---|---|---|---|---|---|---|---|---|"] + rows
    (library / "INDEX.md").write_text("\n".join(text) + "\n", encoding="utf-8")


def export(acs, library, commit):
    exported = []
    for device in list_devices(acs):
        result = acs.request("/api/v1/devices/%s/discovery-export" % device["id"])
        snapshots = result.get("snapshots") or []
        if not snapshots:
            print("skip %s: no discovery snapshot" % device.get("product_class", "?"))
            continue
        latest = snapshots[0]  # newest first
        root = latest.get("root") or "Device."
        ident = identity(acs, device, root)
        evidence = latest.get("evidence") or {}
        manufacturer = ident["Manufacturer"] or evidence.get("manufacturer") or device.get("manufacturer", "")
        product = ident["ProductClass"] or evidence.get("model") or device.get("product_class", "")
        firmware = ident["SoftwareVersion"] or evidence.get("firmware", "")
        directory = library / slug(manufacturer) / slug(product) / slug(firmware)

        meta, params = load_entry(directory)
        types = {c["path"]: c.get("value_type", "") for c in latest.get("capabilities") or [] if c.get("path")}
        for path, writable in (latest.get("names") or {}).items():
            current = params.get(path, {"writable": False, "type": ""})
            params[path] = {"writable": current["writable"] or bool(writable), "type": types.get(path) or current.get("type", "")}

        merged_keys = set(meta.get("merged_command_keys", []))
        new_walk = latest.get("command_key") not in merged_keys
        if new_walk:
            merged_keys.add(latest.get("command_key"))
        skipped = set(meta.get("never_observed", [])) | set(skipped_objects(acs, latest.get("command_key", "")))
        skipped = sorted(s for s in skipped if s not in params)  # a later walk may have seen it
        hardware = sorted(set(meta.get("hardware_versions", [])) | ({ident["HardwareVersion"]} if ident["HardwareVersion"] else set()))
        meta.update({
            "manufacturer": manufacturer,
            "model_name": ident["ModelName"] or meta.get("model_name", ""),
            "product_class": product,
            "oui": device.get("oui", "") or meta.get("oui", ""),
            "hardware_versions": hardware,
            "software_version": firmware,
            "root": root,
            "root_data_model_version": ident["RootDataModelVersion"] or meta.get("root_data_model_version", ""),
            "protocol": latest.get("protocol", "") or meta.get("protocol", ""),
            "parameter_count": sum(1 for p in params if not p.endswith(".")),
            "object_count": sum(1 for p in params if p.endswith(".")),
            "writable_count": sum(1 for p, v in params.items() if v["writable"] and not p.endswith(".")),
            "never_observed": skipped,
            "merged_command_keys": sorted(k for k in merged_keys if k),
            "snapshots_merged": len([k for k in merged_keys if k]),
            "last_discovered_at": max(latest.get("discovered_at", ""), meta.get("last_discovered_at", "")),
            "exported_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
            "acs_commit": commit or meta.get("acs_commit", ""),
            "scope": "Names and access metadata only. Runtime tables (hosts, Wi-Fi clients/events, scans, alarms) are walked at their lowest instance; other tables at most 32 instances.",
        })
        write_entry(directory, meta, params)
        exported.append((directory.relative_to(library).as_posix(), meta["parameter_count"], new_walk))
    write_index(library)
    return exported


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--base-url", required=True)
    parser.add_argument("--library", type=Path, default=DEFAULT_LIBRARY)
    parser.add_argument("--acs-commit", default="", help="ACS build that produced the walks (e.g. `git rev-parse --short HEAD`)")
    args = parser.parse_args()
    token = os.environ.get("ACS_API_TOKEN")
    if not token:
        parser.error("set ACS_API_TOKEN")
    for entry, count, new_walk in export(discovery.ACS(args.base_url, token), args.library, args.acs_commit):
        print("%-60s %5d params %s" % (entry, count, "(new walk merged)" if new_walk else "(already merged)"))
    print("index: %s" % (args.library / "INDEX.md"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
